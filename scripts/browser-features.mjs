const email='features-'+Date.now()+'@example.invalid';
async function credentials(email){await page.getByLabel('邮箱',{exact:true}).fill(email);await page.getByLabel('密码',{exact:true}).fill(password);}
async function createCard(name,timezone){
 await page.goto(base+'/cards/new');
 await page.getByLabel('卡片名称',{exact:true}).fill(name);
 const bank=page.getByRole('combobox',{name:'发卡行',exact:true});
 await bank.fill('不存在的测试银行');
 await bank.press('ArrowDown');
 await expect(bank).not.toHaveAttribute('aria-activedescendant',/.+/);
 await bank.press('Enter');
 await expect(page).toHaveURL(base+'/cards/new');
 await bank.fill('Chase');
 await bank.press('ArrowDown');
 await bank.press('Enter');
 await expect(bank).toHaveValue('Chase');
 await expect(bank).toBeFocused();
 await page.getByRole('combobox',{name:'卡组织',exact:true}).fill('Visa');
 await page.getByRole('option',{name:'Visa',exact:true}).click();
 await page.getByLabel('发行地区（可选）',{exact:true}).selectOption('US');
 if(timezone)await page.getByLabel(/^卡片时区（可选）/).fill(timezone);
 await page.getByRole('button',{name:'保存信用卡',exact:true}).click();
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
 return page.url().split('/').pop();
}
